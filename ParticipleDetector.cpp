// ParticipleDetector.cpp
#include "ParticipleDetector.h"
#include <vector>

// Вход: строка и суффикс.
// Что делает: проверяет совпадение конца строки с суффиксом.
// Выход: результат проверки (true/false).
bool endsWith(const std::string& str, const std::string& suffix) {
    if (str.length() < suffix.length()) {
        return false;
    }
    return str.compare(str.length() - suffix.length(), suffix.length(), suffix) == 0;
}

// Вход: очищенное слово.
// Что делает: проверяет признаки деепричастий (-вшись, -вши, -учи, -ючи, -ячи).
// Выход: true, если слово деепричастие (чтобы исключить ложные срабатывания).
bool isGerund(const std::string& word) {
    static const std::vector<std::string> gerundEndings = {
        "вшись", "вши", "учи", "ючи", "ячи"
    };

    for (size_t i = 0; i < gerundEndings.size(); ++i) {
        if (endsWith(word, gerundEndings[i])) {
            return true;
        }
    }
    return false;
}

// Вход: очищенное слово.
// Что делает: эвристически определяет причастие по характерным суффиксам и родовым/падежным окончаниям.
// Выход: true, если слово является причастием.
bool isParticiple(const std::string& word) {
    // Причастие в русском языке обычно не короче 5 букв
    if (word.length() < 5) {
        return false;
    }

    // Отсекаем деепричастия (например, "разучившись")
    if (isGerund(word)) {
        return false;
    }

    // Список типовых причастных комплексов (суффикс + окончание)
    // Охватывает действительные и страдательные причастия во всех родах и падежах
    static const std::vector<std::string> participleEndings = {
        // Действительные настоящего времени (-ущ-, -ющ-, -ащ-, -ящ-)
        "ущий", "ущая", "ущее", "ущие", "ущего", "ущему", "ущим", "ущих", "ущей", "ущую", "ущими", "ущем",
        "ющий", "ющая", "ющее", "ющие", "ющего", "ющему", "ющим", "ющих", "ющей", "ющую", "ющими", "ющем",
        "ащий", "ащая", "ащее", "ащие", "ащего", "ащему", "ащим", "ащих", "ащей", "ащую", "ащими", "ащем",
        "ящий", "ящая", "ящее", "ящие", "ящего", "ящему", "ящим", "ящих", "ящей", "ящую", "ящими", "ящем",

        // Возвратные настоящего времени (-ся/-сь)
        "ущийся", "ущаяся", "ущееся", "ущиеся", "ущегося", "ущемуся", "ущимся", "ущихся",
        "ющийся", "ющаяся", "ющееся", "ющиеся", "ющегося", "ющемуся", "ющимся", "ющихся",
        "ащийся", "ащаяся", "ащееся", "ащиеся", "ащегося", "ащемуся", "ащимся", "ащихся",
        "ящийся", "ящаяся", "ящееся", "ящиеся", "ящегося", "ящемуся", "ящимся", "ящихся",

        // Действительные прошедшего времени (-вш-, -ш-)
        "вший", "вшая", "вшее", "вшие", "вшего", "вшему", "вшим", "вших", "вшей", "вшую", "вшими", "вшем",
        "ший", "шая", "шее", "шие", "шего", "шему", "шим", "ших", "шей", "шую", "шими", "шем",

        // Возвратные прошедшего времени
        "вшийся", "вшаяся", "вшееся", "вшиеся", "вшегося", "вшемуся", "вшимся", "вшихся",
        "шийся", "шаяся", "шееся", "шиеся", "шегося", "шемуся", "шимся", "шихся",

        // Страдательные настоящего времени (-ем-, -им-)
        "емый", "емая", "емое", "емые", "емого", "емому", "емым", "емых", "емой", "емую", "емыми", "емом",
        "имый", "имая", "имое", "имые", "имого", "имому", "имым", "имых", "имой", "имую", "имыми", "имом",

        // Страдательные прошедшего времени (-нн-, -енн-, -т-)
        "нный", "нная", "нное", "нные", "нного", "нному", "нным", "нных", "нной", "нную", "нными", "нном",
        "енный", "енная", "енное", "енные", "енного", "енному", "енным", "енных", "енной", "енную", "енными", "енном",
        "тый", "тая", "тое", "тые", "того", "тому", "тым", "тых", "той", "тую", "тыми", "том"
    };

    for (size_t i = 0; i < participleEndings.size(); ++i) {
        if (endsWith(word, participleEndings[i])) {
            return true;
        }
    }

    return false;
}