// ParticipleDetector.h
#pragma once
#include <string>

// Вход: строка (строка-источник) и строка-суффикс.
// Что делает: проверяет, оканчивается ли строка на указанный суффикс/окончание.
// Выход: true, если оканчивается; false в противном случае.
bool endsWith(const std::string& str, const std::string& suffix);

// Вход: очищенное слово в нижнем регистре.
// Что делает: проверяет, является ли слово деепричастием (ловушка фильтрации).
// Выход: true, если слово является деепричастием; false иначе.
bool isGerund(const std::string& word);

// Вход: очищенное слово в нижнем регистре.
// Что делает: проверяет, является ли слово русским причастием по характерным формантам.
// Выход: true, если слово определено как причастие; false иначе.
bool isParticiple(const std::string& word);