#pragma once
#include <string>
#include <vector>
#include "Types.h"

// Вход: символ в кодировке Windows-1251.
// Что делает: проверяет принадлежность к русскому алфавиту.
// Выход: true, если символ русский.
bool isRussianLetter(char c);

// Вход: символ в кодировке Windows-1251.
// Что делает: переводит заглавную русскую букву в строчную.
// Выход: символ в нижнем регистре.
char toLowerRus(char c);

// Вход: символ текста.
// Что делает: проверяет, является ли символ завершителем предложения (. ! ?).
// Выход: true, если символ знак пунктуации конца предложения.
bool isSentenceDelimiter(char c);

// Вход: строка токена.
// Что делает: обрезает крайние небуквенные знаки и приводит буквы к нижнему регистру.
// Выход: очищенное слово.
std::string sanitizeWord(const std::string& raw);

// Вход: имя исходного файла, векторы для токенов причастий и структурированных предложений.
// Что делает: посимвольно читает файл без ограничений на объем, нумерует предложения и извлекает причастия.
// Выход: true при успешном разборе; false при ошибке открытия файла.
bool parseTextFile(const std::string& filename,
    std::vector<WordToken>& participles,
    std::vector<SentenceItem>& sentences);

// Вход: путь к выходному файлу и вектор структурированных предложений.
// Что делает: записывает предложения в файл в формате нумерованного списка (как в VS).
// Выход: true при успехе записи; false при ошибке создания файла.
bool saveNumberedSentences(const std::string& filename, const std::vector<SentenceItem>& sentences);