// TextParser.h
#pragma once
#include <string>
#include <vector>
#include "Types.h"

// Вход: символ в кодировке Windows-1251.
// Что делает: безопасно переводит русские и английские буквы в нижний регистр.
// Выход: приведенный символ.
char toLowerChar(char c);

// Вход: символ текста.
// Что делает: проверяет, является ли символ знаком завершения предложения ('.', '!', '?').
// Выход: true, если символ завершает предложение.
bool isSentenceDelimiter(char c);

// Вход: сырая строка-токен из файла.
// Что делает: удаляет знаки препинания по краям, оставляет внутренние дефисы, приводит к нижнему регистру.
// Выход: чистое слово.
std::string sanitizeWord(const std::string& raw);

// Вход: путь к входному файлу и флаг успеха операции.
// Что делает: читает файл любого объема потоком, ведет счетчик предложений, отображает индикацию работы точками и отбирает причастия.
// Выход: массив найденных причастий с привязкой к номерам предложений.
std::vector<WordToken> extractParticiplesFromFile(const std::string& filename, bool& isOk);