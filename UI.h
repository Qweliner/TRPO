#pragma once
#include <string>
#include <vector>
#include "Types.h"

// Вход: минимальное и максимальное допустимое целое число.
// Что делает: организует ввод числа пользователем с защитой от спама при пустом вводе и нажатиях Enter.
// Выход: валидное целое число.
int getSafeIntInput(int minVal, int maxVal);

// Вход: строка с предполагаемым именем файла.
// Что делает: проверяет отсутствие запрещенных символов файловой системы Windows.
// Выход: true, если имя допустимо; false иначе.
bool isValidFilename(const std::string& name);

// Вход: имя файла на диске.
// Что делает: проверяет существование и доступность файла для чтения.
// Выход: true, если файл найден; false иначе.
bool fileExists(const std::string& filename);

// Вход: базовое имя файла без расширения.
// Что делает: формирует уникальное имя с числовым суффиксом в скобках для защиты от перезаписи.
// Выход: свободное имя файла.
std::string getIndexedFilename(const std::string& baseName);

// Вход: имя файла справки.
// Что делает: построчно считывает и отображает инструкцию для пользователя.
// Выход: нет.
void printInstructions(const std::string& helpFile);

// Вход: нет.
// Что делает: предоставляет меню выбора тестового файла или ручного ввода.
// Выход: имя выбранного входного файла или пустая строка при отмене.
std::string selectSourceFileStep();

// Вход: имя файла, список предложений, найденные пары рифм и статистика.
// Что делает: сохраняет разметку предложений и отчет анализа в два выходных файла.
// Выход: нет.
void saveReportStep(const std::string& inputFilename,
    const std::vector<SentenceItem>& sentences,
    const std::vector<RhymePair>& pairs,
    const std::vector<WordStat>& stats);

// Вход: нет.
// Что делает: управляющая функция сквозного анализа текста с повторной проверкой словарей перед стартом.
// Выход: нет.
void runAnalysisPipeline();